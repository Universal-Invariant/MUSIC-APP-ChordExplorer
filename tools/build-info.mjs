#!/usr/bin/env node
/**
 * Injects build metadata (git commit hash, dirty flag, timestamp) into the
 * web bundle by generating src/web/buildinfo.generated.ts before compilation.
 * Run automatically via the `prebuild:web` npm hook; safe to run manually.
 */
import { execSync } from "node:child_process";
import { writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");

function git(cmd) {
  try {
    return execSync(`git ${cmd}`, { cwd: root, encoding: "utf8" }).trim();
  } catch {
    return "";
  }
}

const hash = git("rev-parse --short HEAD") || "unknown";
const branch = git("rev-parse --abbrev-ref HEAD") || "";
const dirty = git("status --porcelain").length > 0;
const builtAt = new Date().toISOString();

const out = `// GENERATED by tools/build-info.mjs — do not edit.
export const BUILD_INFO = {
  commit: "${hash}",
  branch: "${branch}",
  dirty: ${dirty},
  builtAt: "${builtAt}",
} as const;
`;

writeFileSync(join(root, "src", "web", "buildinfo.generated.ts"), out);
console.log(`build-info: ${hash}${dirty ? " (dirty)" : ""} @ ${builtAt}`);
